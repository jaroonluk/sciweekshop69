#!/bin/bash
set -euo pipefail

APP_DIR=/var/www/html
cd "$APP_DIR"

mkdir -p data/uploads data/oauth_pending data/oauth_tokens
chown -R www-data:www-data data || true
chmod -R ug+rwX data || true

DB_HOST="${SCI_DB_HOST:-db}"
DB_PORT="${SCI_DB_PORT:-3306}"
DB_NAME="${SCI_DB_NAME:-sciweekshop}"
DB_USER="${SCI_DB_USER:-sci}"
DB_PASS="${SCI_DB_PASS:-sci}"
EOFFICE_DB="${SCI_EOFFICE_DB:-eoffice}"
PUBLIC_BASE="${SCI_PUBLIC_BASE_URL:-http://localhost:8088}"

# Keep a file config in sync for CLI tools (apply_schema.php, migrate_*.php)
if [ ! -f data/db_config.php ] || [ "${SCI_WRITE_DB_CONFIG:-1}" = "1" ]; then
  cat > data/db_config.php <<EOF
<?php
/** Auto-generated by Docker entrypoint — safe to overwrite. */
return [
  'host' => '${DB_HOST}',
  'port' => ${DB_PORT},
  'dbname' => '${DB_NAME}',
  'user' => '${DB_USER}',
  'pass' => '${DB_PASS}',
  'charset' => 'utf8mb4',
  'eoffice_db' => '${EOFFICE_DB}',
];
EOF
  chown www-data:www-data data/db_config.php || true
fi

echo "[sci-shop] waiting for MySQL at ${DB_HOST}:${DB_PORT} ..."
if command -v wait-for-it >/dev/null 2>&1; then
  wait-for-it "${DB_HOST}:${DB_PORT}" -t 90 --strict -- echo "[sci-shop] MySQL is up"
else
  for i in $(seq 1 90); do
    if php -r "try { new PDO('mysql:host=${DB_HOST};port=${DB_PORT}', '${DB_USER}', '${DB_PASS}'); exit(0);} catch (Throwable \$e) { exit(1);}"; then
      echo "[sci-shop] MySQL is up"
      break
    fi
    sleep 1
    if [ "$i" -eq 90 ]; then
      echo "[sci-shop] MySQL wait timed out" >&2
      exit 1
    fi
  done
fi

ensure_schema() {
  php -r "
    \$host = getenv('SCI_DB_HOST') ?: 'db';
    \$port = (int)(getenv('SCI_DB_PORT') ?: 3306);
    \$user = getenv('SCI_DB_USER') ?: 'sci';
    \$pass = getenv('SCI_DB_PASS') ?: 'sci';
    \$db   = getenv('SCI_DB_NAME') ?: 'sciweekshop';
    \$pdo = new PDO(\"mysql:host=\$host;port=\$port;charset=utf8mb4\", \$user, \$pass, [
      PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
    ]);
    \$n = (int)\$pdo->query('SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA=' . \$pdo->quote(\$db) . \" AND TABLE_NAME='events'\")->fetchColumn();
    exit(\$n > 0 ? 0 : 2);
  "
}

if [ "${SCI_AUTO_SCHEMA:-1}" = "1" ]; then
  if ensure_schema; then
    echo "[sci-shop] schema already present"
  else
    echo "[sci-shop] applying sql/001_schema.sql ..."
    php apply_schema.php
    for f in sql/002_add_committee_role.sql sql/003_apply_extra_questions.sql sql/004_apply_flow.sql sql/005_apply_program.sql; do
      if [ -f "$f" ]; then
        echo "[sci-shop] applying $f ..."
        php -r "
          \$host = getenv('SCI_DB_HOST') ?: 'db';
          \$port = (int)(getenv('SCI_DB_PORT') ?: 3306);
          \$user = getenv('SCI_DB_USER') ?: 'sci';
          \$pass = getenv('SCI_DB_PASS') ?: 'sci';
          \$sql = file_get_contents('${f}');
          \$m = mysqli_init();
          if (!\$m->real_connect(\$host, \$user, \$pass, null, \$port)) {
            fwrite(STDERR, mysqli_connect_error() . PHP_EOL);
            exit(1);
          }
          \$m->set_charset('utf8mb4');
          if (!\$m->multi_query(\$sql)) {
            fwrite(STDERR, \$m->error . PHP_EOL);
            exit(1);
          }
          do { if (\$r = \$m->store_result()) { \$r->free(); } } while (\$m->more_results() && \$m->next_result());
          if (\$m->errno) { fwrite(STDERR, \$m->error . PHP_EOL); exit(1); }
          echo 'OK' . PHP_EOL;
        "
      fi
    done
  fi
fi

if [ ! -f data/auth_secrets.php ]; then
  if [ -n "${GOOGLE_CLIENT_ID:-}" ] && [ -n "${GOOGLE_CLIENT_SECRET:-}" ]; then
    echo "[sci-shop] writing data/auth_secrets.php from env ..."
    export SCI_PUBLIC_BASE_URL="$PUBLIC_BASE"
    php -r "
      \$base = rtrim(getenv('SCI_PUBLIC_BASE_URL') ?: 'http://localhost:8088', '/');
      \$host = parse_url(\$base, PHP_URL_HOST) ?: 'localhost';
      \$emails = array_values(array_filter(array_map('trim', explode(',', getenv('SCI_ALLOWED_EMAILS') ?: ''))));
      \$domains = array_values(array_filter(array_map('trim', explode(',', getenv('SCI_ALLOWED_DOMAINS') ?: ''))));
      \$cfg = [
        'client_id' => getenv('GOOGLE_CLIENT_ID'),
        'client_secret' => getenv('GOOGLE_CLIENT_SECRET'),
        'allowed_emails' => \$emails,
        'allowed_domains' => \$domains,
        'public_base_url' => \$base,
        'public_base_urls' => [\$host => \$base, '127.0.0.1' => preg_replace('#://[^/]+#', '://127.0.0.1', \$base)],
      ];
      file_put_contents('data/auth_secrets.php', \"<?php\\nreturn \" . var_export(\$cfg, true) . \";\\n\");
    "
  else
    echo "[sci-shop] creating placeholder data/auth_secrets.php (set GOOGLE_CLIENT_* to enable Admin login)"
    cat > data/auth_secrets.php <<EOF
<?php
/** Auto-generated for Docker — replace with real Google OAuth values. */
return [
  'client_id' => '',
  'client_secret' => '',
  'allowed_emails' => [],
  'allowed_domains' => [],
  'public_base_url' => '${PUBLIC_BASE}',
  'public_base_urls' => [
    'localhost' => '${PUBLIC_BASE}',
    '127.0.0.1' => 'http://127.0.0.1:8088',
  ],
];
EOF
  fi
  chown www-data:www-data data/auth_secrets.php || true
fi

if [ "${SCI_ENABLE_MINIO:-0}" = "1" ] && [ ! -f data/minio_config.php ]; then
  cat > data/minio_config.php <<EOF
<?php
/** Auto-generated by Docker entrypoint for MinIO profile. */
return [
  'endpoint' => '${MINIO_ENDPOINT:-minio}',
  'port' => ${MINIO_PORT:-9000},
  'use_ssl' => false,
  'insecure_skip_verify' => true,
  'access_key' => '${MINIO_ACCESS_KEY:-sciadmin}',
  'secret_key' => '${MINIO_SECRET_KEY:-scipassword}',
  'bucket' => '${MINIO_BUCKET:-sci-shop}',
  'region' => 'us-east-1',
  'use_path_style_endpoint' => true,
  'prefix' => '',
];
EOF
  chown www-data:www-data data/minio_config.php || true
  echo "[sci-shop] MinIO config enabled"
else
  echo "[sci-shop] using local uploads (set SCI_ENABLE_MINIO=1 + --profile minio for MinIO)"
fi

echo "[sci-shop] starting Apache ..."
exec "$@"
